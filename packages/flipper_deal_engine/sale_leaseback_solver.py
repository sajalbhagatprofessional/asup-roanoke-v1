"""
Sale-Leaseback (SLB) Capital Arbitrage Solver.
Models commercial real estate monetization to recoup acquisition basis rapidly,
allowing the asset holding company to retain the debt-free operating business at near-zero net basis.
Pure Python decimal.Decimal math (0 floats) - AST verified.
"""

from decimal import Decimal, ROUND_HALF_EVEN
from typing import Optional
from pydantic import BaseModel, Field


class SaleLeasebackInput(BaseModel):
    deal_id: str
    asset_name: str
    total_acquisition_cost_usd: Decimal
    facility_sqft: Decimal
    market_nnn_rent_per_sqft_usd: Decimal = Field(default=Decimal("9.00"))
    investor_exit_cap_rate: Decimal = Field(default=Decimal("0.0725"))  # 7.25%
    transaction_broker_fee_pct: Decimal = Field(default=Decimal("0.0400"))  # 4.0%
    baseline_annual_ebitda_usd: Decimal = Field(default=Decimal("400000.00"))

    class Config:
        arbitrary_types_allowed = True


class SaleLeasebackResult(BaseModel):
    deal_id: str
    asset_name: str
    total_acquisition_cost_usd: Decimal
    facility_sqft: Decimal
    annual_nnn_rent_usd: Decimal
    gross_slb_sale_proceeds_usd: Decimal
    broker_closing_costs_usd: Decimal
    net_slb_cash_recouped_usd: Decimal
    net_remaining_equity_basis_usd: Decimal
    capital_recouped_pct: Decimal
    post_slb_adjusted_ebitda_usd: Decimal
    rent_coverage_ratio: Decimal
    is_slb_viable: bool
    is_infinite_return: bool
    flipper_synthesis: str

    class Config:
        arbitrary_types_allowed = True


def solve_sale_leaseback_arbitrage(inp: SaleLeasebackInput) -> SaleLeasebackResult:
    """
    Computes exact institutional sale-leaseback monetization proceeds.
    Enforces pure decimal math without floating-point precision loss.
    """
    if inp.investor_exit_cap_rate <= Decimal("0.00"):
        raise ValueError("Investor exit cap rate must be strictly positive.")

    # 1. Annual NNN rent generated by facility
    annual_nnn_rent = (inp.facility_sqft * inp.market_nnn_rent_per_sqft_usd).quantize(
        Decimal("0.01"), rounding=ROUND_HALF_EVEN
    )

    # 2. Gross sale price to Net-Lease REIT / private 1031 exchange buyer
    gross_proceeds = (annual_nnn_rent / inp.investor_exit_cap_rate).quantize(
        Decimal("0.01"), rounding=ROUND_HALF_EVEN
    )

    # 3. Transaction fees (brokerage, closing, title transfer)
    closing_costs = (gross_proceeds * inp.transaction_broker_fee_pct).quantize(
        Decimal("0.01"), rounding=ROUND_HALF_EVEN
    )

    # 4. Net cash returned to buyer's bank account
    net_cash_recouped = (gross_proceeds - closing_costs).quantize(
        Decimal("0.01"), rounding=ROUND_HALF_EVEN
    )

    # 5. Remaining equity basis in the operating company (OpCo)
    net_remaining_basis = (inp.total_acquisition_cost_usd - net_cash_recouped).quantize(
        Decimal("0.01"), rounding=ROUND_HALF_EVEN
    )

    is_infinite = net_remaining_basis <= Decimal("0.00")

    # 6. Percentage of initial capital recouped on day of SLB closing
    if inp.total_acquisition_cost_usd > Decimal("0.00"):
        recouped_pct = ((net_cash_recouped / inp.total_acquisition_cost_usd) * Decimal("100.00")).quantize(
            Decimal("0.01"), rounding=ROUND_HALF_EVEN
        )
    else:
        recouped_pct = Decimal("100.00")

    # 7. Post-lease EBITDA (OpCo pays rent to the new property owner)
    post_slb_ebitda = (inp.baseline_annual_ebitda_usd - annual_nnn_rent).quantize(
        Decimal("0.01"), rounding=ROUND_HALF_EVEN
    )

    # 8. Rent coverage ratio (EBITDAR / Rent) required by net lease underwriters (typically >= 1.50x)
    if annual_nnn_rent > Decimal("0.00"):
        coverage = (inp.baseline_annual_ebitda_usd / annual_nnn_rent).quantize(
            Decimal("0.0001"), rounding=ROUND_HALF_EVEN
        )
    else:
        coverage = Decimal("99.9999")

    is_viable = coverage >= Decimal("1.3500") and post_slb_ebitda > Decimal("0.00")

    if is_infinite:
        synthesis = (
            f"EXCEPTIONAL CAPITAL ARBITRAGE: Sale-leaseback of {inp.facility_sqft:,} sqft facility at "
            f"{inp.market_nnn_rent_per_sqft_usd}/sqft NNN and {inp.investor_exit_cap_rate * Decimal('100.0')}% cap "
            f"returns ${net_cash_recouped:,.2f}, exceeding total purchase basis by "
            f"${abs(net_remaining_basis):,.2f}. The operating company is owned for $0 net cash (infinite return) "
            f"with ${post_slb_ebitda:,.2f} in residual annual EBITDA at {coverage:.2f}x rent coverage."
        )
    elif is_viable:
        synthesis = (
            f"HIGH-VELOCITY SLB DE-RISK: Net sale proceeds of ${net_cash_recouped:,.2f} recoup "
            f"{recouped_pct}% of acquisition basis within 45 days. Residual equity invested in OpCo is capped at "
            f"${net_remaining_basis:,.2f} against ${post_slb_ebitda:,.2f} pro-forma EBITDA ({coverage:.2f}x coverage)."
        )
    else:
        synthesis = (
            f"MARGINAL / STRESSED SLB: Rent burden of ${annual_nnn_rent:,.2f}/yr compresses post-closing EBITDA "
            f"to ${post_slb_ebitda:,.2f} ({coverage:.2f}x coverage). Net lease investors will require letter of credit "
            f"or seller escrow reserve."
        )

    return SaleLeasebackResult(
        deal_id=inp.deal_id,
        asset_name=inp.asset_name,
        total_acquisition_cost_usd=inp.total_acquisition_cost_usd,
        facility_sqft=inp.facility_sqft,
        annual_nnn_rent_usd=annual_nnn_rent,
        gross_slb_sale_proceeds_usd=gross_proceeds,
        broker_closing_costs_usd=closing_costs,
        net_slb_cash_recouped_usd=net_cash_recouped,
        net_remaining_equity_basis_usd=net_remaining_basis,
        capital_recouped_pct=recouped_pct,
        post_slb_adjusted_ebitda_usd=post_slb_ebitda,
        rent_coverage_ratio=coverage,
        is_slb_viable=is_viable,
        is_infinite_return=is_infinite,
        flipper_synthesis=synthesis,
    )
